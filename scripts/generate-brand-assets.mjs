#!/usr/bin/env node
/**
 * npm run brand
 *
 * Generates the logo, favicons, app icons and Open Graph share images from
 * the brand colours in src/styles/theme.css and the flame paths in
 * src/components/ui/Logo/Logo.tsx. Re-run it after changing brand colours.
 *
 * Output:
 *   public/logo.svg
 *   public/favicon.ico, public/icons/*.png, public/icons/icon.svg
 *   public/og/*.png (1200×630, one per page)
 */
import fs from 'node:fs';
import path from 'node:path';
import matter from 'gray-matter';
import sharp from 'sharp';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const pub = (...p) => path.join(root, 'public', ...p);
fs.mkdirSync(pub('icons'), { recursive: true });
fs.mkdirSync(pub('og'), { recursive: true });

/* ---------- read tokens + flame paths (single sources of truth) ---------- */
const themeCss = fs.readFileSync(path.join(root, 'src/styles/theme.css'), 'utf8');
const token = (name) => {
  const match = themeCss.match(new RegExp(`${name}\\s*:\\s*(#[0-9a-fA-F]{3,8})\\s*;`));
  if (!match) throw new Error(`Token ${name} must be a hex value in theme.css`);
  return match[1];
};
const c = {
  primary: token('--color-primary'),
  secondary: token('--color-secondary'),
  dark: token('--color-dark'),
  cream: token('--color-cream'),
  white: token('--color-white'),
};

const logoTsx = fs.readFileSync(path.join(root, 'src/components/ui/Logo/Logo.tsx'), 'utf8');
const flamePath = (name) => {
  const match = logoTsx.match(new RegExp(`${name}\\s*=\\s*'([^']+)'`));
  if (!match) throw new Error(`Could not find ${name} in Logo.tsx`);
  return match[1];
};
const OUTER = flamePath('FLAME_OUTER');
const INNER = flamePath('FLAME_INNER');

/** Mix two hex colours (like CSS color-mix in srgb) */
const mix = (a, b, weightA) => {
  const parse = (hex) => {
    const h = hex.replace('#', '');
    const full =
      h.length === 3
        ? h
            .split('')
            .map((x) => x + x)
            .join('')
        : h.slice(0, 6);
    return [0, 2, 4].map((i) => parseInt(full.slice(i, i + 2), 16));
  };
  const [ca, cb] = [parse(a), parse(b)];
  return `#${ca
    .map((v, i) =>
      Math.round(v * weightA + cb[i] * (1 - weightA))
        .toString(16)
        .padStart(2, '0'),
    )
    .join('')}`;
};
const ember = mix(mix(c.primary, c.secondary, 0.65), c.dark, 0.85);

const escape = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const FONT = "'DM Sans', 'Liberation Sans', 'DejaVu Sans', Arial, sans-serif";
const MONO = "'JetBrains Mono', 'DejaVu Sans Mono', 'Liberation Mono', monospace";

const flameDefs = (id) => `
  <linearGradient id="${id}" x1="0" y1="1" x2="0.35" y2="0">
    <stop offset="0%" stop-color="${c.primary}"/>
    <stop offset="55%" stop-color="${ember}"/>
    <stop offset="100%" stop-color="${c.secondary}"/>
  </linearGradient>`;
const flame = (id, innerColor = c.cream) =>
  `<path d="${OUTER}" fill="url(#${id})"/><path d="${INNER}" fill="${innerColor}"/>`;

/* ---------- logo.svg ---------- */
const logoSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 260 56" width="260" height="56" role="img" aria-label="Powerflame Energy">
  <defs>${flameDefs('pf-flame')}</defs>
  <g transform="translate(2 4)">${flame('pf-flame')}</g>
  <text x="54" y="31" font-family="${FONT}" font-size="26" font-weight="800" letter-spacing="0.5" fill="${c.dark}">POWERFLAME</text>
  <text x="55" y="47" font-family="${MONO}" font-size="10" font-weight="500" letter-spacing="7.2" fill="${c.primary}">ENERGY</text>
</svg>
`;
// Only overwrite logo.svg if it is missing or was generated by this script,
// so a designer's replacement logo is never lost.
const LOGO_MARKER = '<!-- generated by scripts/generate-brand-assets.mjs -->';
const existingLogo = fs.existsSync(pub('logo.svg')) ? fs.readFileSync(pub('logo.svg'), 'utf8') : '';
if (!existingLogo || existingLogo.includes(LOGO_MARKER)) {
  fs.writeFileSync(pub('logo.svg'), logoSvg.replace('<svg ', `${LOGO_MARKER}\n<svg `));
} else {
  console.log('• Kept your custom public/logo.svg');
}

/* ---------- icons ---------- */
const iconSvg = (size, { padding = 0.16, rounded = true, bg = c.cream } = {}) => {
  const inner = size * (1 - padding * 2);
  const scale = inner / 48;
  const x = (size - 40 * scale) / 2;
  const y = (size - 48 * scale) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
  <defs>${flameDefs('g')}</defs>
  <rect width="${size}" height="${size}" rx="${rounded ? size * 0.22 : 0}" fill="${bg}"/>
  <g transform="translate(${x} ${y}) scale(${scale})">${flame('g')}</g>
</svg>`;
};

fs.writeFileSync(pub('icons', 'icon.svg'), iconSvg(64, { padding: 0.1 }));
const png = (svg) => sharp(Buffer.from(svg)).png({ compressionLevel: 9 }).toBuffer();

await fs.promises.writeFile(pub('icons', 'icon-192.png'), await png(iconSvg(192)));
await fs.promises.writeFile(pub('icons', 'icon-512.png'), await png(iconSvg(512)));
await fs.promises.writeFile(
  pub('icons', 'icon-maskable-512.png'),
  await png(iconSvg(512, { padding: 0.24, rounded: false })),
);
await fs.promises.writeFile(
  pub('icons', 'apple-touch-icon.png'),
  await png(iconSvg(180, { padding: 0.14, rounded: false })),
);

// favicon.ico containing 16, 32 and 48px PNGs
const icoSizes = [16, 32, 48];
const icoImages = await Promise.all(icoSizes.map((s) => png(iconSvg(s, { padding: 0.06 }))));
const header = Buffer.alloc(6 + 16 * icoImages.length);
header.writeUInt16LE(0, 0);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(icoImages.length, 4);
let offset = header.length;
icoImages.forEach((img, i) => {
  const e = 6 + i * 16;
  header.writeUInt8(icoSizes[i] % 256, e);
  header.writeUInt8(icoSizes[i] % 256, e + 1);
  header.writeUInt8(0, e + 2);
  header.writeUInt8(0, e + 3);
  header.writeUInt16LE(1, e + 4);
  header.writeUInt16LE(32, e + 6);
  header.writeUInt32LE(img.length, e + 8);
  header.writeUInt32LE(offset, e + 12);
  offset += img.length;
});
fs.writeFileSync(pub('favicon.ico'), Buffer.concat([header, ...icoImages]));

/* ---------- Open Graph images ---------- */
const wrap = (text, max) => {
  const lines = [];
  let line = '';
  for (const word of text.split(/\s+/)) {
    if ((line + ' ' + word).trim().length > max && line) {
      lines.push(line);
      line = word;
    } else line = (line + ' ' + word).trim();
  }
  if (line) lines.push(line);
  return lines;
};

const ogSvg = ({ eyebrow, title }) => {
  const lines = wrap(title, 24).slice(0, 4);
  const size = lines.length > 3 ? 62 : 70;
  const startY = 330 - ((lines.length - 1) * size * 1.08) / 2;
  const grid = Array.from(
    { length: 20 },
    (_, i) => `<path d="M${i * 64} 0V630M0 ${i * 64}H1200"/>`,
  ).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="630" viewBox="0 0 1200 630">
  <defs>
    ${flameDefs('og')}
    <radialGradient id="glowR"><stop offset="0" stop-color="${c.primary}" stop-opacity="0.38"/><stop offset="1" stop-color="${c.primary}" stop-opacity="0"/></radialGradient>
    <radialGradient id="glowA"><stop offset="0" stop-color="${c.secondary}" stop-opacity="0.5"/><stop offset="1" stop-color="${c.secondary}" stop-opacity="0"/></radialGradient>
    <linearGradient id="fade" x1="0" x2="1"><stop offset="0.3" stop-color="${c.cream}" stop-opacity="1"/><stop offset="1" stop-color="${c.cream}" stop-opacity="0"/></linearGradient>
  </defs>
  <rect width="1200" height="630" fill="${c.cream}"/>
  <g stroke="${c.dark}" stroke-opacity="0.06" stroke-width="1">${grid}</g>
  <circle cx="1020" cy="200" r="420" fill="url(#glowR)"/>
  <circle cx="980" cy="330" r="300" fill="url(#glowA)"/>
  <g transform="translate(860 120) scale(7.6)" opacity="0.95">${flame('og')}</g>
  <rect x="0" y="0" width="760" height="630" fill="url(#fade)" opacity="0.6"/>
  <g transform="translate(72 64)">
    <g transform="scale(1.1)">${flame('og')}</g>
    <text x="56" y="30" font-family="${FONT}" font-size="28" font-weight="800" letter-spacing="0.5" fill="${c.dark}">POWERFLAME</text>
    <text x="57" y="48" font-family="${MONO}" font-size="11" letter-spacing="8" fill="${c.primary}">ENERGY</text>
  </g>
  <g transform="translate(72 ${startY - size - 34})">
    <rect width="${Math.min(560, eyebrow.length * 11.5 + 56)}" height="38" rx="19" fill="${mix(c.primary, c.white, 0.09)}" stroke="${mix(c.primary, c.white, 0.16)}"/>
    <circle cx="22" cy="19" r="5" fill="${c.primary}"/>
    <text x="38" y="25" font-family="${MONO}" font-size="16" letter-spacing="2.5" fill="${c.primary}">${escape(eyebrow.toUpperCase())}</text>
  </g>
  ${lines
    .map(
      (l, i) =>
        `<text x="72" y="${startY + i * size * 1.08}" font-family="${FONT}" font-size="${size}" font-weight="800" letter-spacing="-2" fill="${c.dark}">${escape(l)}</text>`,
    )
    .join('\n  ')}
  <text x="72" y="566" font-family="${MONO}" font-size="20" fill="${mix(c.dark, c.cream, 0.75)}">powerflame.co.zw  ·  Hatfield, Harare</text>
  <rect x="0" y="618" width="1200" height="12" fill="url(#og)"/>
</svg>`;
};

const articlesDir = path.join(root, 'src/content/articles');
const articlePages = fs
  .readdirSync(articlesDir)
  .filter((f) => f.endsWith('.mdx'))
  .map((f) => {
    const { data } = matter(fs.readFileSync(path.join(articlesDir, f), 'utf8'));
    return {
      file: `articles-${f.replace(/\.mdx$/, '')}`,
      eyebrow: data.category ?? 'Article',
      title: data.title,
    };
  });

const pages = [
  { file: 'default', eyebrow: 'LPG gas Harare', title: 'Clean energy for every kitchen' },
  { file: 'home', eyebrow: 'LPG gas Harare', title: 'Clean energy for every kitchen' },
  { file: 'about', eyebrow: 'About us', title: 'Proudly Zimbabwean, powered by trust' },
  {
    file: 'services',
    eyebrow: 'Our services',
    title: 'Gas refills, cylinders, appliances & installation',
  },
  {
    file: 'services-lpg-gas-refills',
    eyebrow: 'Gas refills Harare',
    title: 'Accurately weighed LPG gas refills',
  },
  {
    file: 'services-gas-cylinders-and-accessories',
    eyebrow: 'Gas cylinders Zimbabwe',
    title: 'Gas cylinders & accessories',
  },
  {
    file: 'services-gas-appliances-and-safety-equipment',
    eyebrow: 'Appliances & safety',
    title: 'Gas stoves & safety equipment',
  },
  {
    file: 'services-gas-installation-and-repairs',
    eyebrow: 'Gas installation Harare',
    title: 'Gas installation & repairs',
  },
  { file: 'industries', eyebrow: 'Who we serve', title: 'LPG for homes, kitchens and businesses' },
  {
    file: 'gas-safety',
    eyebrow: 'LPG safety Zimbabwe',
    title: 'The practical guide to using gas safely',
  },
  { file: 'faq', eyebrow: 'FAQ', title: 'Your questions about gas, answered' },
  { file: 'articles', eyebrow: 'Articles & guides', title: 'Practical guides to cooking with gas' },
  { file: 'contact', eyebrow: 'Get in touch', title: 'Talk to our Hatfield team' },
  { file: 'privacy-policy', eyebrow: 'Legal', title: 'Privacy policy' },
  ...articlePages,
];

for (const page of pages) {
  const buffer = await sharp(Buffer.from(ogSvg(page)))
    .png({ compressionLevel: 9, palette: true, quality: 90 })
    .toBuffer();
  fs.writeFileSync(pub('og', `${page.file}.png`), buffer);
}

console.log(
  `✔ Generated logo, icons, favicon and ${pages.length} Open Graph images from theme.css`,
);
